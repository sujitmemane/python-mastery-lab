"""Practice: extract text with slices."""

# Level 1 - Print the first five characters.
text = "programming"
print(text[:5])


# Level 2 - Print the last three characters.
text = "developer"
print(text[-3:])


# Level 3 - Print every second character.
text = "abcdefghij"
print(text[::2])


# Level 4 - Reverse the text and print the first four characters.
text = "stressed"
print(text[::-1][:4])

