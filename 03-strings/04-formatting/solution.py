"""Solutions for string formatting practice."""

name = "Asha"
city = "Pune"
print(f"{name} lives in {city}.")

price = 12.5
quantity = 3
print(f"Total: ${price * quantity:.2f}")

score = 0.934
print(f"Score: {score:.1%}")

item = "Notebook"
quantity = 2
unit_price = 4.75
print(f"{item} x {quantity}: ${quantity * unit_price:.2f}")
